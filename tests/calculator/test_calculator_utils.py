"""calculator.utils text helpers and the parsers that rely on them.

VASP data: only the real pymatgen files in fixtures/vasp (see PROVENANCE.md).
"""

import os
import re

import pytest

from matsimpy.calculator.utils import clean_lines, micro_pyawk

VASP_DIR = os.path.join(os.path.dirname(__file__), "fixtures", "vasp")


def _lines(name):
    with open(os.path.join(VASP_DIR, name)) as handle:
        return handle.read().splitlines()


def test_clean_lines_strips_comments_on_a_real_incar():
    raw = _lines("INCAR")  # two comment-only lines, one trailing "# omit flag ..."
    assert raw[:2] == ["#Generated by VASPTemplateInput", "# Here are the tags"]
    assert "ENCUTFOCK=0  # omit flag for high quality calculations" in raw

    cleaned = clean_lines(raw)
    assert not any("#" in line for line in cleaned)
    assert cleaned[0] == "LREAL=Auto"
    assert "ENCUTFOCK=0" in cleaned
    assert "" not in cleaned
    # without dropping empty lines, every input line maps to one output line
    assert len(clean_lines(raw, remove_empty_lines=False)) == len(raw)


def test_lammps_data_header_accepts_trailing_comments(tmp_path):
    # Not VASP data: the pymatgen-2026.10.24 test files contain no LAMMPS data file.
    pytest.importorskip("pandas")
    from matsimpy.calculator.lammps.data import LammpsData

    path = tmp_path / "comments.data"
    path.write_text(
        "LAMMPS data file  # header\n\n"
        "2 atoms   # two Ar atoms\n1 atom types\n\n"
        "0.0 10.0 xlo xhi   # box x\n0.0 10.0 ylo yhi\n0.0 10.0 zlo zhi\n\n"
        "Masses\n\n1 39.948\n\n"
        "Atoms  # atomic\n\n1 1 0.0 0.0 0.0\n2 1 5.0 5.0 5.0\n"
    )
    data = LammpsData.from_file(str(path), atom_style="atomic")
    assert len(data.atoms) == 2
    assert data.box.bounds == [[0.0, 10.0]] * 3


def test_micro_pyawk_runs_records_with_predicates_on_a_real_outcar():
    path = os.path.join(VASP_DIR, "OUTCAR")
    with open(path) as handle:
        expected = [float(m[1]) for m in re.finditer(r"POMASS =\s*\S+; ZVAL\s*=\s*(\S+)", handle.read())]
    assert expected == [1.0, 10.0, 6.0]

    def collect(results, match):
        results.setdefault("zval", []).append(float(match[1]))

    def count_lines(results, _line):
        results["lines"] = results.get("lines", 0) + 1

    results = micro_pyawk(
        path,
        [
            [r"ZVAL\s*=\s*(\S+)", lambda _results, line: "POMASS" in line, collect],
        ],
        postdebug=count_lines,
    )
    assert results["zval"] == expected
    with open(path) as handle:
        assert results["lines"] == sum(1 for _ in handle)


def test_micro_pyawk_rejects_the_old_dict_interface():
    path = os.path.join(VASP_DIR, "OSZICAR")
    with pytest.raises(TypeError, match="records"):
        micro_pyawk(path, {"key": r"F="})
    with pytest.raises(ValueError, match="regex, predicate, action"):
        micro_pyawk(path, [[r"F=", None]])
